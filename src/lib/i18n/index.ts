// Lower-cased canonical code -> canonical Locale key (case-insensitive lookup
// while exported keys keep BCP-47 casing).
const lowerToLocale = new Map<string, Locale>(
  (Object.keys(locales) as Locale[]).map((code) => [code.toLowerCase(), code]),
);

// Explicit aliases: legacy/duplicate codes and script/region variants the
// provider emits that map onto a canonical dictionary. Generic base-language
// fallback (e.g. "es-MX" -> "es") is handled below; these are the cases the base
// split alone would get wrong.
const ALIASES: Record<string, Locale> = {
  iw: "he",          // legacy Hebrew
  jw: "jv",          // legacy Javanese
  tl: "fil",         // Tagalog -> Filipino
  in: "id",          // legacy Indonesian
  nb: "no", nn: "no",// Norwegian Bokmål/Nynorsk -> Norwegian
  "zh-cn": "zh", "zh-hans": "zh", "zh-sg": "zh",
  "zh-tw": "zh-TW", "zh-hk": "zh-TW", "zh-hant": "zh-TW",
  "fr-fr": "fr",
  "pt-pt": "pt", "pt-br": "pt-BR",
};

/**
 * Resolve any incoming platform-language code to a supported UI locale.
 * Case-insensitive; unknown/invalid codes fall back to English. Order: exact
 * canonical match, explicit alias, then base-language fallback (strip the
 * region/script subtag) via alias or canonical map.
 */
export function resolveLocale(language: string | null): Locale {
  const normalized = language?.trim().toLowerCase();
  if (!normalized) return "en";

  const exact = lowerToLocale.get(normalized);
  if (exact) return exact;

  const alias = ALIASES[normalized];
  if (alias) return alias;

  const base = normalized.split(/[-_]/)[0];
  if (base && base !== normalized) {
    const baseAlias = ALIASES[base];
    if (baseAlias) return baseAlias;
    const baseExact = lowerToLocale.get(base);
    if (baseExact) return baseExact;
  }

  return "en";
}

export function getDirection(locale: Locale): "ltr" | "rtl" {
  return RTL_LOCALES.has(locale) ? "rtl" : "ltr";
}

